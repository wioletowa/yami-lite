// Язык интерфейса: русский (исходный) или английский. Надписи в коде пишутся по-русски;
// при английском текст подменяется по таблице прямо при отрисовке (ui.text*), поэтому язык
// переключается на лету. Строки с подстановками — макросом tf!("…", "…", args).
// Какой язык — решает yami_px::i18n.

use std::collections::HashMap;
use std::sync::OnceLock;

pub use yami_px::i18n::{en, set, translated};

/// перевод целой надписи (английский по PAIRS); нет — как есть
pub fn tr(s: &str) -> &str {
    if !translated() {
        return s;
    }
    table().get(s).copied().unwrap_or(s)
}

/// пара прямо в коде: русская и английская
pub fn select<'a>(ru: &'a str, en: &'a str) -> &'a str {
    if translated() {
        en
    } else {
        ru
    }
}



/// строка с подстановками: русский и английский шаблоны рядом (литералы: Rust проверяет
/// аргументы при сборке)
#[macro_export]
macro_rules! tf {
    ($ru:literal, $en:literal $(, $a:expr)* $(,)?) => {
        if $crate::i18n::en() {
            format!($en $(, $a)*)
        } else {
            format!($ru $(, $a)*)
        }
    };
}

fn table() -> &'static HashMap<&'static str, &'static str> {
    static T: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    T.get_or_init(|| PAIRS.iter().copied().collect())
}


